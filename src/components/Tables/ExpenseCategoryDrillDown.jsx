const formatNumber = (value) => {
    if (
        value === null ||
        value === undefined ||
        value === ""
    ) {
        return "â€”";
    }

    const number = Number(value);

    if (Number.isNaN(number)) {
        return "â€”";
    }

    return number.toLocaleString("en-US");
};

/* =========================================================
   FORMAT MONTH VALUE
   AED â†’ AED Millions

   Example:
   8,364,319.95 â†’ AED 8.36M
   123224.59    â†’ AED 0.12M
========================================================= */

const formatMonthValue = (value) => {
    if (
        value === null ||
        value === undefined ||
        value === ""
    ) {
        return "â€”";
    }

    /*
     * Convert the incoming value to a number first.
     *
     * This ensures that:
     *
     * 8364319.95
     *      â†“
     * 8.36431995
     *      â†“
     * AED 8.36M
     */
    const number = Number(
        typeof value === "string"
            ? value.replace(/,/g, "")
            : value
    );

    if (!Number.isFinite(number)) {
        return "â€”";
    }

    const millions = number / 1_000_000;

    return `AED ${millions.toLocaleString("en-US", {
        minimumFractionDigits: 2,
        maximumFractionDigits: 2,
    })}M`;
};

/* =========================================================
   FORMAT DATA AS OF
========================================================= */

const formatDataAsOf = (value) => {
    if (!value) {
        return "â€”";
    }

    const valueString = String(value);

    const dateOnlyMatch = valueString.match(
        /^(\d{4})-(\d{2})-(\d{2})$/
    );

    if (dateOnlyMatch) {
        const [, year, month, day] = dateOnlyMatch;

        const date = new Date(
            Number(year),
            Number(month) - 1,
            Number(day)
        );

        return date.toLocaleDateString("en-GB", {
            day: "2-digit",
            month: "short",
            year: "numeric",
        });
    }

    const date = new Date(value);

    if (Number.isNaN(date.getTime())) {
        return valueString;
    }

    return date.toLocaleDateString("en-GB", {
        day: "2-digit",
        month: "short",
        year: "numeric",
    });
};

/* =========================================================
   GET MONTH VALUE
========================================================= */

const getMonthValue = (
    monthData,
    month
) => {
    if (!monthData) {
        return null;
    }

    if (Array.isArray(monthData)) {
        const monthItem = monthData.find(
            (item) =>
                item?.month === month ||
                item?.month_name === month ||
                item?.monthName === month
        );

        return (
            monthItem?.value ??
            monthItem?.actual ??
            monthItem?.monthly_actual ??
            null
        );
    }

    return (
        monthData?.[month] ??
        monthData?.[month.toLowerCase()] ??
        null
    );
};

